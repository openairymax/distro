# log.sh — 失败诊断日志截尾（被构建驱动 source）
#
# 构建驱动把子步骤输出重定向到日志文件，失败时只回传路径会导致 CI 日志
# 看不到真实错误。统一在此截取尾部若干行，保证调用方与 CI 编排的诊断
# 口径一致。默认 60 行是 run 42175199476 的教训：12 行窗口恰好只装下
# rpm 的 "Bad exit status (%check)" 摘要，真正的断言输出切在窗口上沿
# 之外，多跑一轮才能定位。
#
# 调用约定：log_tail <日志> [行数] [前缀]，向 stderr 输出；日志不存在或
# 为空时静默返回 0，不影响调用方退出码。
# ===========================================================================

log_tail()
{
    local log="$1" lines="${2:-60}" prefix="${3:-  }"
    [ -s "${log}" ] || return 0
    tail -n "${lines}" "${log}" | sed "s/^/${prefix}/" >&2
}
