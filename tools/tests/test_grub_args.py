# test_grub_args.py — 启动参数持久来源（grub_args.sh）行为回归
#
# 脚本要在安装末期把启动画面参数写进 /etc/default/grub 并关闭 os-prober，
# 因为 kickstart 的 bootloader --append 只进安装器生成的那一份 grub.cfg。
# --no-regen 只改写输入文件，不碰块设备，因此可在临时目录里判定；每个用例
# 只破坏一个前提，覆盖三种失败：参数缺失、探测开关未关、文件不可读。
#
# 生成阶段（regen / ESP 副本）用 --mkconfig 注入假生成器，在临时目录里走完
# 与真机相同的分支。这一层是 0.0.3 UEFI 装机失败的现场：cfg 由命令替换取
# 回，函数内赋值随子 shell 丢失，cfg 为空后 fail，安装器在最后一个 %post
# 中止；此前只测 --no-regen，恰好绕过整段路径。
#
# Author: Liren Wang <wangliren@spharx.cn>
# Version: 0.0.3
# ===========================================================================

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

BASE = Path(__file__).resolve().parents[2]
SCRIPT = BASE / "boot" / "grub_args.sh"
SH = shutil.which("sh") or "/bin/sh"

# 安装器生成的形态：参数行带 console，os-prober 以注释形式给出。
STOCK = """\
GRUB_TIMEOUT=3
GRUB_DEFAULT=saved
GRUB_TERMINAL_OUTPUT="console"
GRUB_CMDLINE_LINUX="console=tty0 console=ttyS0,115200"
#GRUB_DISABLE_OS_PROBER=true
GRUB_DISABLE_RECOVERY="true"
"""


class GrubArgsTest(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.root = Path(self._tmp.name)
        self.defaults = self.root / "grub"
        self.state = self.root / "state" / "grub-args"

    def tearDown(self):
        self._tmp.cleanup()

    def write(self, body=STOCK):
        self.defaults.write_text(body, encoding="utf-8")
        return self.defaults

    def run_args(self, *args):
        env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin")}
        return subprocess.run([SH, str(SCRIPT), *args], env=env,
                              text=True, capture_output=True)

    def apply(self, *extra, body=None):
        self.write(body or STOCK)
        return self.run_args("--defaults", str(self.defaults),
                             "--state", str(self.state),
                             "--no-regen", *extra)

    def check(self):
        return self.run_args("--defaults", str(self.defaults),
                             "--state", str(self.state), "--check")

    def fake_mk(self, ok=True):
        # 生成器只认 -o 的落点：$1 是 -o，$2 是目标文件
        path = self.root / "mkconfig"
        body = ("#!/bin/sh\nprintf 'menuentry x {}\\n' > \"$2\"\n"
                if ok else "#!/bin/sh\nexit 1\n")
        path.write_text(body, encoding="utf-8")
        path.chmod(0o755)
        return path

    def regen(self, *extra, cfg_body="# generated by anaconda\n"):
        self.write()
        cfg = self.root / "grub.cfg"
        cfg.write_text(cfg_body, encoding="utf-8")
        res = self.run_args("--defaults", str(self.defaults),
                            "--state", str(self.state), "--cfg", str(cfg),
                            *extra)
        return res, cfg

    def text(self):
        return self.defaults.read_text(encoding="utf-8")

    def cmdline(self):
        for line in self.text().splitlines():
            if line.startswith("GRUB_CMDLINE_LINUX="):
                return line.split("=", 1)[1].strip('"')
        self.fail("GRUB_CMDLINE_LINUX absent")

    def prober(self):
        values = [line.split("=", 1)[1] for line in self.text().splitlines()
                  if line.startswith("GRUB_DISABLE_OS_PROBER=")]
        self.assertEqual(len(values), 1, self.text())
        return values[0]

    def test_syntax_is_posix(self):
        res = subprocess.run([SH, "-n", str(SCRIPT)], text=True,
                             capture_output=True)
        self.assertEqual(res.returncode, 0, res.stderr)

    def test_args_appended(self):
        res = self.apply()
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertEqual(self.cmdline(),
                         "console=tty0 console=ttyS0,115200 rhgb quiet")
        self.assertEqual(self.prober(), "true")
        self.assertIn("updated:", res.stdout)

    def test_other_lines_kept(self):
        self.apply()
        lines = self.text().splitlines()
        self.assertEqual(lines[0], "GRUB_TIMEOUT=3")
        self.assertEqual(lines[1], "GRUB_DEFAULT=saved")
        self.assertEqual(lines[2], 'GRUB_TERMINAL_OUTPUT="console"')
        self.assertEqual(lines[-1], 'GRUB_DISABLE_RECOVERY="true"')

    def test_idempotent(self):
        self.apply()
        first = self.text()
        res = self.apply(body=first)
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("unchanged:", res.stdout)
        self.assertEqual(self.text(), first)

    def test_unquoted_normalized(self):
        # 手改过的文件可能没有引号；生成器读不出这种行，必须归一化
        self.apply(body='GRUB_TIMEOUT=3\nGRUB_CMDLINE_LINUX=console=tty0\n')
        self.assertEqual(self.cmdline(), "console=tty0 rhgb quiet")
        self.assertNotIn("GRUB_CMDLINE_LINUX=console", self.text())

    def test_commented_prober_replaced(self):
        # 注释行若不替换而是另起一行，配置里就出现两条同名赋值，后者生效
        self.apply()
        self.assertNotIn("#GRUB_DISABLE_OS_PROBER", self.text())
        self.assertEqual(self.prober(), "true")

    def test_prober_appended_when_absent(self):
        body = STOCK.replace("#GRUB_DISABLE_OS_PROBER=true\n", "")
        self.apply(body=body)
        self.assertEqual(self.prober(), "true")

    def test_cmdline_appended_when_absent(self):
        body = STOCK.replace(
            'GRUB_CMDLINE_LINUX="console=tty0 console=ttyS0,115200"\n', "")
        self.apply(body=body)
        self.assertEqual(self.cmdline(), "rhgb quiet")

    def test_custom_append(self):
        self.apply("--append", "console=ttyAMA0,115200")
        self.assertEqual(self.cmdline(), "console=tty0 console=ttyS0,115200 "
                                         "console=ttyAMA0,115200")
        self.assertEqual(self.prober(), "true")

    def test_no_state_without_regen(self):
        # --no-regen 只判定改写；状态文件是安装期落地的凭证，不能由它伪造
        self.apply()
        self.assertFalse(self.state.exists())

    def test_check_converged(self):
        self.apply()
        res = self.check()
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("ok:", res.stdout)

    def test_check_missing_tokens(self):
        self.write()
        res = self.check()
        self.assertEqual(res.returncode, 1)
        self.assertIn("missing: rhgb", res.stdout)
        self.assertIn("missing: quiet", res.stdout)

    def test_check_prober_off(self):
        body = STOCK.replace("#GRUB_DISABLE_OS_PROBER=true",
                             "GRUB_DISABLE_OS_PROBER=false")
        body = body.replace('GRUB_CMDLINE_LINUX="console=tty0 '
                            'console=ttyS0,115200"',
                            'GRUB_CMDLINE_LINUX="console=tty0 rhgb quiet"')
        self.write(body)
        res = self.check()
        self.assertEqual(res.returncode, 1)
        self.assertIn("GRUB_DISABLE_OS_PROBER is not true", res.stdout)

    def test_defaults_absent(self):
        res = self.run_args("--defaults", str(self.defaults),
                            "--state", str(self.state), "--no-regen")
        self.assertEqual(res.returncode, 1)
        self.assertIn("fail: no", res.stdout)

    def test_bad_option(self):
        res = self.run_args("--regen")
        self.assertEqual(res.returncode, 2)
        self.assertIn("usage:", res.stderr)

    def test_cfg_resolved_from_etc(self):
        # 回归：cfg 必须由 pick_cfg 打印、调用方赋值。曾经在函数里直接赋全局，
        # 命令替换把它丢在子 shell 里，cfg 空串 → 生成步骤无落点 → 装机中止。
        self.write()
        etc = self.root / "etc"
        etc.mkdir()
        real = self.root / "boot" / "grub.cfg"
        real.parent.mkdir()
        real.write_text("menuentry 'anaconda' {}\n", encoding="utf-8")
        (etc / "grub2-efi.cfg").symlink_to(real)
        res = self.run_args("--defaults", str(self.defaults), "--etc", str(etc),
                            "--state", str(self.state),
                            "--mkconfig", str(self.fake_mk()))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        resolved = str(real.resolve())
        self.assertIn("cfg=" + resolved, res.stdout)
        self.assertIn("cfg=" + resolved,
                      self.state.read_text(encoding="utf-8"))
        self.assertIn("menuentry", real.read_text(encoding="utf-8"))

    def test_cfg_absent_fails(self):
        res = self.run_args("--defaults", str(self.defaults),
                            "--state", str(self.state),
                            "--mkconfig", str(self.fake_mk()),
                            "--etc", str(self.root / "no-etc"))
        self.assertEqual(res.returncode, 1)
        self.assertIn("fail: no", res.stdout)

    def test_regen_writes_state(self):
        res, cfg = self.regen("--mkconfig", str(self.fake_mk()))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("regenerated:", res.stdout)
        state = self.state.read_text(encoding="utf-8")
        self.assertIn("cfg=" + str(cfg), state)
        self.assertIn("args=rhgb quiet", state)

    def test_regen_failure_keeps_previous(self):
        # 生成失败时旧配置是唯一的引导凭据，必须原样留回并显式 skip
        res, cfg = self.regen("--mkconfig", str(self.fake_mk(ok=False)),
                              cfg_body="menuentry 'anaconda' {}\n")
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("skip: kept previous", res.stdout)
        self.assertEqual(cfg.read_text(encoding="utf-8"),
                         "menuentry 'anaconda' {}\n")

    def test_regen_without_generator(self):
        res, _ = self.regen("--mkconfig", str(self.root / "absent"))
        self.assertEqual(res.returncode, 1)
        self.assertIn("unavailable", res.stdout)

    def test_esp_copy_refreshed(self):
        esp = self.root / "esp"
        copy = esp / "EFI" / "airymaxos" / "grub.cfg"
        copy.parent.mkdir(parents=True)
        copy.write_text("stale\n", encoding="utf-8")
        res, cfg = self.regen("--esp", str(esp),
                              "--mkconfig", str(self.fake_mk()))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("brand copy refreshed:", res.stdout)
        self.assertEqual(copy.read_text(encoding="utf-8"),
                         cfg.read_text(encoding="utf-8"))

    def font(self, name="unicode.pf2", body="pf2\n"):
        path = self.root / name
        path.write_text(body, encoding="utf-8")
        return path

    def test_font_lands_beside_cfg(self):
        # 字体必须落在生效配置同目录——那正是 grubx64.efi 内嵌的 prefix。
        # 落到品牌副本旁边时 cfg 断言全绿，屏幕仍是固件默认（B50 的 800x600）。
        res, cfg = self.regen("--mkconfig", str(self.fake_mk()),
                              "--font", str(self.font()))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("font placed:", res.stdout)
        self.assertEqual((cfg.parent / "fonts" / "unicode.pf2").read_text(
            encoding="utf-8"), "pf2\n")

    def test_font_unchanged_not_rewritten(self):
        src = self.font()
        self.regen("--mkconfig", str(self.fake_mk()), "--font", str(src))
        res, _ = self.regen("--mkconfig", str(self.fake_mk()), "--font", str(src))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertNotIn("font placed:", res.stdout)

    def test_font_absent_degrades(self):
        # 缺字体是观感与分辨率问题，不是中止安装的理由
        res, cfg = self.regen("--mkconfig", str(self.fake_mk()),
                              "--font", str(self.root / "absent.pf2"))
        self.assertEqual(res.returncode, 0, res.stdout + res.stderr)
        self.assertIn("font source absent", res.stdout)
        self.assertFalse((cfg.parent / "fonts").exists())


if __name__ == "__main__":
    unittest.main()
